"""Eval-power harness for the cached constrained-choice lane.

Item 1 of the VPD-TRM roadmap: size the constrained-decode probe so per-family
target deltas resolve below ``MAX_RESOLVABLE_DELTA``. The cached 4D ARC head tops
out at 62 unique items, so powered probe sets must be regenerated by re-scoring a
larger ARC slice. This module does everything *except* the model run:

- ``measure_power`` reports the achieved per-family resolution of any scored
  sample set (cached or freshly generated).
- ``project_scale`` estimates how many raw items the scoring run needs, from the
  cached failure-rate and family-share distribution, at a chosen family
  granularity.
- ``build_challenge_cards`` / ``emit_scoring_spec`` materialize a ready-to-run
  card slice plus the exact constrained-decode probe invocations.

A "target" probe is the set of *failing* samples in a family; a family's
"non-target" probe is the whole evaluated complement, matching the non-target
denominator used by ``head_to_head.evaluate_candidate``. The binding constraint
is therefore target count: failures fractionate across families, while the
non-target pool is the entire eval grid.
"""

from __future__ import annotations

import math
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

import numpy as np

from param_decomp.experiments.trm_basis_constrained_edits.common import (
    CHOICE_DIM,
    LETTER_LABELS,
    ChoiceSample,
)

MIN_TARGET_PER_FAMILY = 50
MIN_NONTARGET = 200
MAX_RESOLVABLE_DELTA = 0.02

Granularity = Literal["top_target_runner", "top_target", "target"]
GRANULARITIES: tuple[Granularity, ...] = ("top_target_runner", "top_target", "target")


def family_key_for(sample: ChoiceSample, granularity: Granularity) -> str | None:
    """Family key for a *failing* sample, or ``None`` if the model was correct.

    ``top_target_runner`` matches ``head_to_head.failure_families``; the coarser
    keys collapse families so that fewer, larger target probes are formed.
    """
    if sample.baseline_hit:
        return None
    top = sample.top_action()
    target = sample.candidate_actions[sample.target_position]
    runner = sample.runner_up_action()
    label = sample.label_family
    match granularity:
        case "top_target_runner":
            return f"{top}->{target}:{runner}:{label}"
        case "top_target":
            return f"{top}->{target}:{label}"
        case "target":
            return f"{target}:{label}"


@dataclass(frozen=True)
class FamilyPower:
    family_key: str
    label_family: str
    n_target: int
    n_nontarget: int
    resolvable_target_delta: float
    resolvable_nontarget_delta: float
    target_powered: bool
    nontarget_powered: bool
    powered: bool


@dataclass(frozen=True)
class PowerReport:
    granularity: Granularity
    n_samples: int
    n_failures: int
    n_families: int
    n_families_target_powered: int
    n_families_fully_powered: int
    worst_resolvable_target_delta: float
    passes: bool
    families: tuple[FamilyPower, ...]


def _resolvable_delta(count: int) -> float:
    return 1.0 / count if count > 0 else math.inf


def measure_power(
    samples: list[ChoiceSample],
    *,
    granularity: Granularity,
    min_target: int = MIN_TARGET_PER_FAMILY,
    min_nontarget: int = MIN_NONTARGET,
    max_delta: float = MAX_RESOLVABLE_DELTA,
) -> PowerReport:
    """Measure per-family eval resolution of a scored sample set."""
    assert samples, "no samples to measure"
    n_total = len(samples)
    target_counts: Counter[str] = Counter()
    labels: dict[str, str] = {}
    for sample in samples:
        key = family_key_for(sample, granularity)
        if key is None:
            continue
        target_counts[key] += 1
        labels[key] = sample.label_family

    families: list[FamilyPower] = []
    for key, n_target in target_counts.items():
        n_nontarget = n_total - n_target
        target_delta = _resolvable_delta(n_target)
        nontarget_delta = _resolvable_delta(n_nontarget)
        target_powered = n_target >= min_target
        nontarget_powered = n_nontarget >= min_nontarget
        families.append(
            FamilyPower(
                family_key=key,
                label_family=labels[key],
                n_target=n_target,
                n_nontarget=n_nontarget,
                resolvable_target_delta=round(target_delta, 6),
                resolvable_nontarget_delta=round(nontarget_delta, 6),
                target_powered=target_powered,
                nontarget_powered=nontarget_powered,
                powered=target_powered and nontarget_powered and target_delta <= max_delta,
            )
        )
    families.sort(key=lambda fam: (-fam.n_target, fam.family_key))

    powered = [fam for fam in families if fam.powered]
    target_powered = [fam for fam in families if fam.target_powered]
    worst = max((fam.resolvable_target_delta for fam in target_powered), default=math.inf)
    return PowerReport(
        granularity=granularity,
        n_samples=n_total,
        n_failures=sum(target_counts.values()),
        n_families=len(families),
        n_families_target_powered=len(target_powered),
        n_families_fully_powered=len(powered),
        worst_resolvable_target_delta=round(worst, 6) if math.isfinite(worst) else worst,
        passes=len(powered) > 0 and worst <= max_delta,
        families=tuple(families),
    )


@dataclass(frozen=True)
class FamilyProjection:
    family_key: str
    cached_failcount: int
    cached_share: float
    expected_target_at_planned: float
    required_items: int


@dataclass(frozen=True)
class ScaleProjection:
    granularity: Granularity
    cached_unique_items: int
    cached_fail_rate: float
    planned_items: int
    min_support: int
    n_families: int
    required_items_top_family: int
    required_items_all_families: int
    planned_powers_top_family: bool
    planned_powers_all_families: bool
    families: tuple[FamilyProjection, ...]


def project_scale(
    cached_samples: list[ChoiceSample],
    *,
    granularity: Granularity,
    planned_items: int,
    min_target: int = MIN_TARGET_PER_FAMILY,
    min_support: int = 2,
) -> ScaleProjection:
    """Project how many scored items reach ``min_target`` failures per family.

    Uses the cached failure-rate and family-share distribution as the estimator:
    ``expected_target = n_items * fail_rate * family_share``. Families seen only
    ``< min_support`` times in the cache are too noisy to project and are dropped
    from the "all families" requirement (but still reported).
    """
    assert cached_samples, "no cached samples to project from"
    n_total = len(cached_samples)
    fail_counts: Counter[str] = Counter()
    for sample in cached_samples:
        key = family_key_for(sample, granularity)
        if key is not None:
            fail_counts[key] += 1
    n_failures = sum(fail_counts.values())
    assert n_failures > 0, "cached sample set has no failures to project from"
    fail_rate = n_failures / n_total

    families: list[FamilyProjection] = []
    for key, count in fail_counts.most_common():
        share = count / n_failures
        per_item_target = fail_rate * share
        required = math.ceil(min_target / per_item_target) if per_item_target > 0 else 0
        families.append(
            FamilyProjection(
                family_key=key,
                cached_failcount=count,
                cached_share=round(share, 6),
                expected_target_at_planned=round(planned_items * per_item_target, 3),
                required_items=required,
            )
        )

    supported = [fam for fam in families if fam.cached_failcount >= min_support]
    required_top = families[0].required_items if families else 0
    required_all = max((fam.required_items for fam in supported), default=required_top)
    return ScaleProjection(
        granularity=granularity,
        cached_unique_items=n_total,
        cached_fail_rate=round(fail_rate, 6),
        planned_items=planned_items,
        min_support=min_support,
        n_families=len(families),
        required_items_top_family=required_top,
        required_items_all_families=required_all,
        planned_powers_top_family=planned_items >= required_top,
        planned_powers_all_families=planned_items >= required_all,
        families=tuple(families),
    )


def build_challenge_cards(
    parquet_path: Path,
    *,
    n_items: int,
    seed: int,
    env_id: str = "arc_challenge",
) -> list[dict[str, object]]:
    """Build ``n_items`` constrained-choice cards from an ARC parquet slice.

    Only clean A-D items with a valid ``answerKey`` are eligible. ``trajectory_id``
    encodes the parquet row index so the constrained-decode probe can rejoin the
    source row.
    """
    import pandas as pd

    assert parquet_path.exists(), f"missing ARC parquet: {parquet_path}"
    df = pd.read_parquet(parquet_path)
    eligible: list[int] = []
    for index in range(len(df)):
        row = df.iloc[index]
        labels = tuple(str(label) for label in row["choices"]["label"])
        answer = str(row.get("answerKey")).strip()
        if labels == LETTER_LABELS and answer in LETTER_LABELS:
            eligible.append(index)
    assert len(eligible) >= n_items, f"only {len(eligible)} clean A-D items, need {n_items}"
    rng = np.random.default_rng(seed)
    chosen = sorted(int(i) for i in rng.choice(eligible, size=n_items, replace=False))

    cards: list[dict[str, object]] = []
    for index in chosen:
        row = df.iloc[index]
        pairs = [
            (str(label).strip(), str(text).strip())
            for label, text in zip(row["choices"]["label"], row["choices"]["text"], strict=True)
        ]
        candidates = [label for label, _ in pairs]
        assert len(candidates) == CHOICE_DIM
        prompt_lines = [str(row["question"]).strip(), "", "Choose one option from this fixed list:"]
        prompt_lines.extend(f"- {label}: {text}" for label, text in pairs)
        cards.append(
            {
                "env_id": env_id,
                "trajectory_id": f"{env_id}_{index}",
                "step": 0,
                "candidate_prompt": "\n".join(prompt_lines).strip(),
                "candidate_actions": candidates,
                "target_action": str(row.get("answerKey")).strip(),
                "normalized_target_action": str(row.get("answerKey")).strip(),
                "source_path": str(parquet_path),
                "source_index": index,
                "choice_count": len(candidates),
                "status": "matched",
            }
        )
    return cards


def build_mmlu_cards(
    parquet_path: Path,
    *,
    n_items: int,
    seed: int,
    env_id: str,
) -> list[dict[str, object]]:
    """Build numeric 4-choice cards from an mmlu subject parquet.

    mmlu rows carry ``choices`` (a length-4 list of option texts) and ``answer``
    (a 0-based index); options are labelled 1-4 so the card is a ``numeric``
    label family recognised by ``common.label_family``.
    """
    import pandas as pd

    assert parquet_path.exists(), f"missing mmlu parquet: {parquet_path}"
    df = pd.read_parquet(parquet_path)
    eligible = [
        index
        for index in range(len(df))
        if len(list(df.iloc[index]["choices"])) == CHOICE_DIM
        and int(df.iloc[index]["answer"]) in range(CHOICE_DIM)
    ]
    take = min(n_items, len(eligible))
    rng = np.random.default_rng(seed)
    chosen = sorted(int(i) for i in rng.choice(eligible, size=take, replace=False))

    cards: list[dict[str, object]] = []
    for index in chosen:
        row = df.iloc[index]
        texts = [str(text).strip() for text in row["choices"]]
        candidates = [str(position + 1) for position in range(CHOICE_DIM)]
        prompt_lines = [str(row["question"]).strip(), "", "Choose one option from this fixed list:"]
        prompt_lines.extend(f"- {label}: {text}" for label, text in zip(candidates, texts, strict=True))
        cards.append(
            {
                "env_id": env_id,
                "trajectory_id": f"{env_id}_{index}",
                "step": 0,
                "candidate_prompt": "\n".join(prompt_lines).strip(),
                "candidate_actions": candidates,
                "target_action": str(int(row["answer"]) + 1),
                "normalized_target_action": str(int(row["answer"]) + 1),
                "source_path": str(parquet_path),
                "source_index": index,
                "choice_count": CHOICE_DIM,
                "status": "matched",
            }
        )
    return cards


def probe_commands(
    *,
    card_file: Path,
    env_id: str,
    n_items: int,
    seeds: list[int],
    score_root: Path,
    tesseract_root: Path,
) -> list[dict[str, object]]:
    """Per-seed constrained-decode probe invocations for the powered slice."""
    commands: list[dict[str, object]] = []
    for seed in seeds:
        out_dir = score_root / f"powered_arc_challenge_{n_items}_seed{seed}"
        commands.append(
            {
                "seed": seed,
                "out_dir": str(out_dir),
                "score_file": str(out_dir / "choice_constrained_sample_scores.jsonl"),
                "argv": [
                    "python",
                    "param_decomp/experiments/trm_choice_constrained_decode_probe.py",
                    "--tesseract-root",
                    str(tesseract_root),
                    "--card-file",
                    str(card_file),
                    "--out-dir",
                    str(out_dir),
                    "--env-id",
                    env_id,
                    "--examples",
                    str(n_items),
                    "--seed",
                    str(seed),
                ],
            }
        )
    return commands
